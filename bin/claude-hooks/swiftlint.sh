#!/usr/bin/env bash

# Claude Code PostToolUse hook: lint the just-edited Swift file with SwiftLint.
#
# Reads the hook payload (JSON) on stdin, extracts the file path, and runs it
# through `make lint-swift` so the hook uses the exact same SwiftLint binary and
# configuration as the project lint command. On violations, prints them to
# stderr and exits 2 so Claude Code feeds them back to the model for
# self-correction.

f=$(jq -r '.tool_input.file_path // empty')
case "$f" in
    *.swift) ;;
    *) exit 0 ;;
esac

cd "${CLAUDE_PROJECT_DIR:-.}" || exit 0

# Only lint files inside this project. A session rooted here can span additional
# working directories, and sibling repos ship their own .swiftlint.yml — linting
# their files against GutenbergKit's rule set would report violations that are
# not violations there, and the hook exits 2, so those would be fed back as
# errors to fix. Resolve both sides so symlinked paths compare correctly.
project_dir=$(pwd -P)
case "$f" in
    /*) abs=$f ;;
    *) abs=$project_dir/$f ;;
esac
case "$abs" in
    "$project_dir"/*) ;;
    *) exit 0 ;;
esac

# The SwiftPM plugin needs a toolchain. Exit quietly rather than failing the
# edit when this runs somewhere Xcode isn't available.
command -v xcrun >/dev/null 2>&1 || exit 0

# Generated by `make build` and excluded from .swiftlint.yml; skip the ~10s
# plugin startup entirely for files that can never produce violations.
case "$f" in
    */ios/Sources/GutenbergKit/Gutenberg/*) exit 0 ;;
esac

out=$(make lint-swift SWIFT_LINT_PATHS="$f" 2>&1)
status=$?

# SwiftLint exits non-zero for `error`-severity violations, but only prints to
# stdout for warnings, so check both. Keep just the `file:line:col:` diagnostics
# so the model sees violations without SwiftPM's wrapper noise (e.g. "Command
# found error violations ... in package").
violations=$(printf '%s\n' "$out" | grep -E '^.+:[0-9]+:[0-9]+: (warning|error):')

if [ -n "$violations" ]; then
    printf '%s\n' "$violations" >&2
    exit 2
fi

# Surface genuine tooling failures (e.g. a broken BuildTools checkout) instead
# of silently passing.
if [ "$status" -ne 0 ]; then
    printf '%s\n' "$out" >&2
    exit 2
fi
